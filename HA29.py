from typing import Generator
# Генератор Фибоначчи
# Создайте генератор, который генерирует последовательность Фибоначчи бесконечно,
# возвращая по одному числу за раз.
# Последовательность Фибоначчи — это ряд чисел,
# где каждое следующее число равно сумме двух предыдущих.
# Начинается с 0 и 1.
def fibonacci() -> Generator[int, None, None]:
    """
    Бесконечный генератор последовательности Фибоначчи.
    :return:генератор целых чисел последовательности Фибоначчи

    """
    num1, num2 = 0, 1
    while True:
        yield num1
        num1, num2 = num2, num1+num2

gen = fibonacci()

