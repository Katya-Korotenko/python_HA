# Генератор уникальных элементов
# Создайте генератор, который принимает список элементов и выдаёт только уникальные значения,
# сохраняя порядок их появления в исходном списке.
# Данные:
data = [3, 1, 2, 3, 4, 1, 5, 2, 6, 7, 5, 8]

def element(data:list[int])-> Generator[int, None, None]:
    """
    Генератор уникальных элементов списка с сохранением порядка.

    :param data: список целых чисел
    :return: генератор уникальных целых чисел без повторений
    """
    seen = set()
    for item in data:
        if item not in seen:
            seen.add(item)
            yield item


