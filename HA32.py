# Обработка завершена: 2025-03-24 14:06:29
# Сохранение файла: 2025-03-24 14:06:29

def make_logger() -> Callable[[Any], list[str] | None]:
    """
    Фабрика логгеров событий.

    :return: функция-логгер которая сохраняет события с временем и возвращает список
    """
    events: list[str] = []

    def log(event: str | None = None) -> list[str] | None:
        if event is None:
            return events
        else:
            events.append(f"{event}: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")

    return log

