# Фабрика функций округления
# Создайте функцию make_rounder(), которая принимает количество знаков
# для округления и возвращает другую функцию.
# Полученная функция должна принимать число и возвращать его,
# округлённое до указанного ранее количества знаков после запятой.
def make_rounder(digits: int) -> Callable[[float], float]:
    """
    Фабрика  функций округления.

    :param digits: количество знаков после запятой
    :return: функция которая округляет число до указанного количества знаков
    """

    def rounder(number: float) -> float:
        return round(number, digits)
    return rounder

