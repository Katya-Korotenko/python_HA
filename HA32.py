# Рамка вокруг вывода
# Создайте декоратор frame, который оборачивает результат функции рамкой из 50 символов -,
# выводя по строке до и после вызова функции.
# Пример декорируемой функции:
# def say_hello():
#     print("Привет, игрок!")
# Пример вывода:
# --------------------------------------------------
# Привет, игрок!
# --------------------------------------------------

def frame(func: Callable[[], None]) -> Callable[[], None]:
    """
    Декоратор который оборачивает вывод функции рамкой из 50 символов.

    :param func: декорируемая функция
    :return: обёрнутая функция с рамкой
    """

    def wrapper():
        print("-" * 50)
        func()
        print("-" * 50)
    return wrapper

@frame
def say_hello() -> None:
    """Выводит приветственное сообщение игроку."""
    print("Привет, игрок!")


say_hello()
